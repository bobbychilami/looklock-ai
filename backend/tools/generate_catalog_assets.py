"""Original demo product imagery for the LOOKLOCK seed catalog.

Every catalog image in this project is generated by this script. Nothing is
scraped from a retailer, and no third-party photography is bundled, so the demo
assets carry no licensing risk.

Why a hand-written renderer instead of an image library:

* the File API only accepts JPEG and PNG, so vector assets would have to be
  rasterised at request time;
* adding Pillow or cairosvg to the backend's runtime dependencies for the sake of
  ~26 flat-lay illustrations is not worth it;
* `zlib` and `struct` are enough to emit a valid PNG, so the generator runs on a
  bare Python install and stays reproducible.

Run it from the repository root:

    python backend/tools/generate_catalog_assets.py

Images are written to `backend/app/catalog/assets/`. They are committed, so the
application never needs to run this at start-up. Re-run it only when a catalogue
entry is added or its colour changes.

The output is deliberately abstract: a garment silhouette on warm paper, in the
manner of an editorial product flat. It reads clearly at thumbnail size, which
is all the UI needs, and it is unmistakably demo material rather than a
photograph of a real product.
"""

