def generate(target: Path | None = None, assets: Iterable[Asset] | None = None) -> list[Path]:
    directory = target or ASSET_DIR
    written: list[Path] = []
    for filename, draw, base_y in assets or ASSETS:
        canvas = garment_scene(draw, base_y=base_y)
        path = directory / filename
        canvas.save(path)
        written.append(path)
    return written


def main(argv: Sequence[str]) -> int:
    target = Path(argv[1]).resolve() if len(argv) > 1 else ASSET_DIR
    written = generate(target)
    total = sum(path.stat().st_size for path in written)
    print(f"wrote {len(written)} images to {target} ({total / 1024:.0f} KB total)")
    return 0


