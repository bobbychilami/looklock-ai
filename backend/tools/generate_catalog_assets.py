def draw_necklace(cloth: Color, *, accent: Color = CHAMPAGNE) -> Callable[[Canvas], None]:
    def paint(canvas: Canvas) -> None:
        # Nested opaque ellipses, painted large to small, leave a beaded chain.
        rings = 9
        for index in range(rings):
            t = index / (rings - 1)
            canvas.ellipse(
                CX,
                560,
                120 + t * 190,
                150 + t * 250,
                blend(PAPER_TOP, cloth, 0.22 + 0.5 * t),
            )
        canvas.ellipse(CX, 890, 34, 40, accent)
        canvas.rect(CX - 5, 780, 10, 74, accent)

    return paint


