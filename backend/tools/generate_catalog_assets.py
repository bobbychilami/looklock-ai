GLOW_BANDS = 26
GLOW_REACH_X = 520
GLOW_REACH_Y = 560
GLOW_CENTRE_Y = 0.47


def blend(base: Color, tint: Color, amount: float) -> Color:
    """Pre-mix two colours so a fill can be written opaque."""
    amount = max(0.0, min(1.0, amount))
    return (
        round(base[0] + (tint[0] - base[0]) * amount),
        round(base[1] + (tint[1] - base[1]) * amount),
        round(base[2] + (tint[2] - base[2]) * amount),
    )


def paint_backdrop(canvas: Canvas) -> None:
    """Paper gradient, soft central glow, and a corner vignette - all opaque."""
    centre_x = CANVAS_W / 2
    for y in range(canvas.height):
        t = y / max(canvas.height - 1, 1)
        base = blend(PAPER_TOP, PAPER_BOTTOM, t)

        # Elliptical vignette, darkest at the corners. Cheap: folded into the
        # pre-blended band colours rather than composited per pixel.
        vx = centre_x / (CANVAS_W * 0.78)
        vy = (y - CANVAS_H * 0.5) / (CANVAS_H * 0.72)
        base = blend(base, VIGNETTE, min(1.0, (vx * vx + vy * vy) ** 0.5) ** 1.5 * 0.6)

        dy = (y + 0.5 - CANVAS_H * GLOW_CENTRE_Y) / GLOW_REACH_Y
        if abs(dy) >= 1.0:
            canvas.span(y, 0, canvas.width, base)
            continue

        half = GLOW_REACH_X * (1.0 - dy * dy) ** 0.5
        vertical_falloff = 1.0 - abs(dy)
        canvas.span(y, 0, centre_x - half, base)
        for band in range(GLOW_BANDS):
            near = band / GLOW_BANDS
            far = (band + 1) / GLOW_BANDS
            canvas.span(
                y,
                centre_x - half + 2 * half * near,
                centre_x - half + 2 * half * far,
                blend(
                    base,
                    GLOW,
                    (1.0 - abs(near + far - 1.0) ** 2) ** 1.5 * vertical_falloff * 0.55,
                ),
            )
        canvas.span(y, centre_x + half, canvas.width, base)

    canvas.rect(0, CANVAS_H - 176, CANVAS_W, 2, blend(PAPER_BOTTOM, FLOOR, 0.6))


def paint_floor_shadow(canvas: Canvas, centre_x: float, base_y: float, width: float) -> None:
    """Contact shadow as nested opaque ellipses, lightest first."""
    paper = blend(PAPER_TOP, PAPER_BOTTOM, min(1.0, (base_y + 6) / max(canvas.height - 1, 1)))
    rings = 12
    for index in range(rings):
        t = index / (rings - 1)
        canvas.ellipse(
            centre_x,
            base_y + 6,
            width * (0.42 + t * 0.62),
            20 + t * 16,
            blend(paper, FLOOR, 0.10 + 0.5 * t),
        )


def garment_scene(draw: Callable[[Canvas], None], *, base_y: float = 1046) -> Canvas:
    canvas = Canvas(CANVAS_W, CANVAS_H)
    paint_backdrop(canvas)
    draw(canvas)
    paint_floor_shadow(canvas, CANVAS_W / 2, base_y, 250)
    return canvas


