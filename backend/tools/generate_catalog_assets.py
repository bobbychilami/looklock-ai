class Canvas:
    """A minimal RGB raster built from horizontal spans.

    Performance note: an opaque run is written as a single `bytes * n` slice
    assignment, which runs in C. A translucent run costs a Python-level loop
    per pixel, so translucent fills are reserved for small details (seams,
    plackets, embroidery). Large soft effects - the paper gradient, the glow
    behind the garment, the floor shadow - are quantised into opaque bands whose
    colours are pre-blended, which keeps them fast and keeps them looking smooth.

    Edges are antialiased horizontally by giving the two end pixels of each run
    fractional coverage. The shapes here are garment silhouettes with mostly
    near-vertical edges, so that is where the aliasing would otherwise show.
    """

    def __init__(self, width: int, height: int) -> None:
        self.width = width
        self.height = height
        self.buffer = bytearray(width * height * 3)
        #: 8-bit coverage, one byte per pixel. Only meaningful for a layer that
        #: will be composited onto another canvas - the backdrop leaves it zero.
        #: It exists so a garment can be rendered on its own and then dropped onto
        #: the backdrop with a shadow derived from its actual silhouette, which is
        #: the difference between a garment lying on a sweep and a garment pasted
        #: onto one.
        self.coverage = bytearray(width * height)

    # -- primitives -------------------------------------------------------- #

    def _blend_pixel(self, y: int, x: int, color: Color, alpha: float) -> None:
        if alpha <= 0 or not (0 <= x < self.width):
            return
        offset = (y * self.width + x) * 3
        inverse = 1.0 - alpha
        buffer = self.buffer
        buffer[offset] = int(buffer[offset] * inverse + color[0] * alpha)
        buffer[offset + 1] = int(buffer[offset + 1] * inverse + color[1] * alpha)
        buffer[offset + 2] = int(buffer[offset + 2] * inverse + color[2] * alpha)
        index = y * self.width + x
        covered = int(alpha * 255)
        if covered > self.coverage[index]:
            self.coverage[index] = covered

    def span(
        self, y: float, x_start: float, x_end: float, color: Color, alpha: float = 1.0
    ) -> None:
        """Paint one horizontal run, antialiasing its two end pixels."""
        if alpha <= 0 or x_end <= x_start:
            return
        row = int(y)
        if not (0 <= row < self.height):
            return
        left = max(0.0, min(x_start, self.width - 1.0))
        right = max(0.0, min(x_end, float(self.width)))
        if right <= left:
            return
        first, last = int(left), int(right)
        if first == last:
            self._blend_pixel(row, first, color, alpha * (right - left))
            return

        self._blend_pixel(row, first, color, alpha * (1.0 - (left - first)))
        self._blend_pixel(row, last, color, alpha * (right - last))

        interior_start, interior_stop = first + 1, last
        if interior_stop <= interior_start:
            return
        count = interior_stop - interior_start
        offset = (row * self.width + interior_start) * 3
        if alpha >= 1.0:
            self.buffer[offset : offset + count * 3] = bytes(color) * count
            self.coverage[
                row * self.width + interior_start : row * self.width + interior_stop
            ] = b"\xff" * count
        else:
            inverse = 1.0 - alpha
            buffer = self.buffer
            pixel = bytes(color)
            for index in range(count):
                at = offset + index * 3
                buffer[at] = int(buffer[at] * inverse + pixel[0] * alpha)
                buffer[at + 1] = int(buffer[at + 1] * inverse + pixel[1] * alpha)
                buffer[at + 2] = int(buffer[at + 2] * inverse + pixel[2] * alpha)

    def polygon(self, points: Sequence[Point], color: Color, alpha: float = 1.0) -> None:
        """Even-odd scanline fill, crossing-accurate so edges stay smooth."""
        if len(points) < 3:
            return
        ys = [point[1] for point in points]
        y_start = max(0, int(min(ys)))
        y_stop = min(self.height, int(max(ys)) + 1)
        count = len(points)
        for y in range(y_start, y_stop):
            centre = y + 0.5
            crossings: list[float] = []
            for index in range(count):
                x1, y1 = points[index]
                x2, y2 = points[(index + 1) % count]
                if (y1 <= centre < y2) or (y2 <= centre < y1):
                    t = (centre - y1) / (y2 - y1)
                    crossings.append(x1 + t * (x2 - x1))
            crossings.sort()
            for pair in range(0, len(crossings) - 1, 2):
                self.span(y, crossings[pair], crossings[pair + 1], color, alpha)

    # -- shading ------------------------------------------------------------ #
    #
    # A flat fill reads as clip art; a garment reads as cloth because light falls
    # unevenly across it. `shade` is sampled per scanline and per column band so a
    # garment body gets a cylindrical highlight, darker roll-off at the seams, and
    # a vertical falloff toward the hem. That is most of what separates a
    # product-photograph impression from a vector icon.

    #: Column bands per scanline when shading. Each band is written as a single
    #: opaque `bytes * n` slice, so the cost stays in C; raising this trades file
    #: size for smoothness.
    SHADE_BANDS = 40

    def _shade_color(self, base: Color, light: float) -> Color:
        """Apply a `light` value in roughly [-0.35, +0.35] to `base`.

        Positive light moves toward white, negative toward black, with a warm bias
        on the lit side because the studio sweep is warm paper.
        """
        tint = (255, 252, 246) if light >= 0 else (24, 20, 18)
        return blend(base, tint, min(0.45, abs(light)))

    def shaded_polygon(
        self,
        points: Sequence[Point],
        base: Color,
        shade: Callable[[float, float, float, float], float] | None = None,
        alpha: float = 1.0,
    ) -> None:
        """Fill a polygon with lighting derived from `shade`.

        `shade` receives `(x, y, u, v)` - absolute pixel coordinates plus the
        point's position within the polygon's own bounding box - and returns a
        light value. Coordinates are absolute as well as relative so a caller can
        line shading terms up across a garment body and its sleeves, which is what
        stops each piece looking separately lit.
        """
        if len(points) < 3:
            return
        xs = [point[0] for point in points]
        ys = [point[1] for point in points]
        min_x, max_x = min(xs), max(xs)
        min_y, max_y = min(ys), max(ys)
        box_w = max(1.0, max_x - min_x)
        box_h = max(1.0, max_y - min_y)

        y_start = max(0, int(min_y))
        y_stop = min(self.height, int(max_y) + 1)
        count = len(points)
        bands = self.SHADE_BANDS

        for y in range(y_start, y_stop):
            centre = y + 0.5
            crossings: list[float] = []
            for index in range(count):
                x1, y1 = points[index]
                x2, y2 = points[(index + 1) % count]
                if (y1 <= centre < y2) or (y2 <= centre < y1):
                    t = (centre - y1) / (y2 - y1)
                    crossings.append(x1 + t * (x2 - x1))
            crossings.sort()
            for pair in range(0, len(crossings) - 1, 2):
                left, right = crossings[pair], crossings[pair + 1]
                if right <= left:
                    continue
                if shade is None:
                    self.span(y, left, right, base, alpha)
                    continue
                span_w = right - left
                for band in range(bands):
                    near = left + span_w * band / bands
                    far = left + span_w * (band + 1) / bands
                    mid_x = (near + far) / 2
                    self.span(
                        y,
                        near,
                        far,
                        self._shade_color(
                            base,
                            shade(
                                mid_x,
                                centre,
                                (mid_x - min_x) / box_w,
                                (centre - min_y) / box_h,
                            ),
                        ),
                        alpha,
                    )

    def bloom(
        self,
        cx: float,
        cy: float,
        radius: float,
        color: Color,
        strength: float = 0.5,
        steps: int = 18,
    ) -> None:
        """A soft radial falloff, painted as nested translucent ellipses.

        Used for the sheen on silk and the bloom inside a highlight, where a hard
        edge would read as a sticker rather than as light.
        """
        for index in range(steps):
            t = index / max(steps - 1, 1)
            self.ellipse(
                cx,
                cy,
                radius * (0.25 + t * 0.85),
                radius * (0.25 + t * 0.85) * 0.72,
                color,
                alpha=strength * (1.0 - t) ** 2,
            )

    def rect(
        self, x: float, y: float, w: float, h: float, color: Color, alpha: float = 1.0
    ) -> None:
        for row in range(max(0, int(y)), min(self.height, int(y + h) + 1)):
            self.span(row, x, x + w, color, alpha)

    def line(
        self,
        x1: float,
        y1: float,
        x2: float,
        y2: float,
        thickness: float,
        color: Color,
        alpha: float = 1.0,
    ) -> None:
        """A rotated rectangle standing in for a thick stroke."""
        dx, dy = x2 - x1, y2 - y1
        length = (dx * dx + dy * dy) ** 0.5 or 1.0
        nx, ny = -dy / length * thickness / 2, dx / length * thickness / 2
        self.polygon(
            [(x1 + nx, y1 + ny), (x2 + nx, y2 + ny), (x2 - nx, y2 - ny), (x1 - nx, y1 - ny)],
            color,
            alpha,
        )

    def ellipse(
        self, cx: float, cy: float, rx: float, ry: float, color: Color, alpha: float = 1.0
    ) -> None:
        if rx <= 0 or ry <= 0:
            return
        y_start = max(0, int(cy - ry))
        y_stop = min(self.height, int(cy + ry) + 1)
        for y in range(y_start, y_stop):
            dy = (y + 0.5 - cy) / ry
            if abs(dy) > 1:
                continue
            half = rx * (1.0 - dy * dy) ** 0.5
            self.span(y, cx - half, cx + half, color, alpha)

    # -- output ------------------------------------------------------------- #

    def save(self, path: Path) -> None:
        write_png(path, self.width, self.height, self.buffer)


def write_png(path: Path, width: int, height: int, pixels: bytes | bytearray) -> None:
    """Encode 8-bit RGB into a PNG. Filter type 0 on every scanline."""
    raw = bytearray()
    stride = width * 3
    for y in range(height):
        raw.append(0)
        raw.extend(pixels[y * stride : (y + 1) * stride])

    def chunk(tag: bytes, payload: bytes) -> bytes:
        return (
            struct.pack(">I", len(payload))
            + tag
            + payload
            + struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF)
        )

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + chunk(b"IEND", b"")
    )


