/**
 * The result.
 *
 * The generated image is the entire point of the screen, so it gets the room.
 * The expiry is stated up front rather than in fine print: the URL is a
 * presigned YouCam link and we do not hold a copy, so a refresh in three days
 * genuinely will not work and the user deserves to know that now.
 */

import { useEffect, useState } from 'react'
import { Link, Navigate, useParams } from 'react-router-dom'

import { assetUrl } from '@/config/env'
import { getProductTryOnJob } from '@/api/looklock'
import type { ProductTryOnStatusResponse } from '@/api/types'
import { AppShell } from '@/components/layout/AppShell'
import { ProductImage } from '@/components/product/ProductTile'
import { Button } from '@/components/ui/Button'
import { useLookSession } from '@/state/looklock'

export default function Result() {
  const { jobId } = useParams<{ jobId: string }>()
  const { recommendation } = useLookSession()
  const [status, setStatus] = useState<ProductTryOnStatusResponse | null>(null)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    if (!jobId) return
    const controller = new AbortController()
    getProductTryOnJob(jobId, controller.signal)
      .then(setStatus)
      .catch((cause: unknown) => {
        if (cause instanceof DOMException && cause.name === 'AbortError') return
        setError(cause instanceof Error ? cause.message : 'Could not load this result.')
      })
    return () => controller.abort()
  }, [jobId])

  if (!recommendation) return <Navigate to="/create" replace />

  const product = status?.product_id
    ? recommendation.looks
        .flatMap((look) => look.items)
        .find((item) => item.product_id === status.product_id)
    : undefined

  const resultUrl = assetUrl(status?.result_url)

  return (
    <AppShell>
      <div className="mx-auto max-w-5xl px-6 py-16">
        <header className="flex flex-col gap-3 text-center">
          <p className="eyebrow">Your try-on</p>
          <h1 className="text-title text-ink-950">
            {product ? `How ${product.name} looks on you` : 'Your result'}
          </h1>
          {product && <p className="text-sm text-ink-700">{product.color}</p>}
        </header>

        {error && (
          <p className="mx-auto mt-10 max-w-md border-l-2 border-accent-600 bg-accent-100/40 px-5 py-4 text-sm text-accent-700">
            {error}
          </p>
        )}

        {resultUrl ? (
          <div className="mt-10 grid gap-10 lg:grid-cols-2">
            <figure className="overflow-hidden rounded-editorial border border-ink-200 bg-white">
              <img
                src={resultUrl}
                alt={product ? `You wearing ${product.name}` : 'Your virtual try-on result'}
                className="w-full object-cover"
              />
              <figcaption className="border-t border-ink-100 px-4 py-3 text-xs text-ink-500">
                Generated by YouCam AI Clothes Virtual Try-On V4.0. Fit and drape are approximate.
              </figcaption>
            </figure>

            {product && (
              <div className="flex flex-col gap-6">
                <div className="flex items-center gap-4 border-b border-ink-200 pb-6">
                  <ProductImage product={product} className="size-20 shrink-0 rounded-editorial" />
                  <div className="flex flex-col gap-1">
                    <p className="font-medium text-ink-950">{product.name}</p>
                    <p className="text-sm text-ink-700">{product.description}</p>
                  </div>
                </div>

                <ul className="flex flex-col gap-2 text-xs leading-relaxed text-ink-500">
                  {status?.notes.map((note) => (
                    <li key={note}>- {note}</li>
                  ))}
                  <li>
                    - Try-on progress is kept in memory only, so a backend restart loses this job.
                  </li>
                </ul>

                <div className="flex flex-col gap-3">
                  <Link to="/shop">
                    <Button size="lg" className="w-full">
                      Shop this look
                    </Button>
                  </Link>
                  <Link to="/looks">
                    <Button variant="secondary" className="w-full">
                      Try another look
                    </Button>
                  </Link>
                </div>
              </div>
            )}
          </div>
        ) : (
          !error && (
            <p className="mt-16 text-center text-sm text-ink-500">Loading your result...</p>
          )
        )}
      </div>
    </AppShell>
  )
}
